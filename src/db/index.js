// The database: PostgreSQL.
//
// LifeAdmin was written against SQLite (Node's built-in node:sqlite), whose file lives on one machine's
// disk. A host that starts the application on demand has no such disk, so the data now lives in a
// PostgreSQL server (DATABASE_URL), and, where none is named (development, the test suite), in PGlite:
// PostgreSQL itself, running inside this process, kept in a folder.
//
// The rest of the application still speaks the dialect it was written in. The four helpers below take the
// same SQL as before and translate the few things PostgreSQL says differently (see `translate`). What
// changed for every caller is one thing only: the helpers answer later, so each call is awaited.
//
// Dates stay what they were: text, in UTC, as 'YYYY-MM-DD HH:MM:SS'. Nothing that compares or shows them had
// to change, and a row reads the same in either database.
const { AsyncLocalStorage } = require('node:async_hooks');
const fs = require('fs');
const path = require('path');

const DATA_DIR = path.join(__dirname, '..', '..', 'data');
// Overridable so that the test suite can point at a disposable database. With PostgreSQL in the process it
// names a folder, not a file.
const DEFAULT_DB_PATH = path.join(DATA_DIR, 'pg');
const DB_PATH = process.env.LIFEADMIN_DB_PATH || DEFAULT_DB_PATH;
// Read when the database is opened, not when this file is loaded: a test that loads this module before it
// has named its disposable database must still get that one. And a test that named none gets nothing,
// instead of quietly writing into the developer's own database.
function embeddedPath() {
  const chosen = process.env.LIFEADMIN_DB_PATH;
  if (!chosen && process.env.NODE_ENV === 'test') throw new Error('Tests need their own database: set LIFEADMIN_DB_PATH (test/helpers.js startApp does) before the database is first used.');
  return chosen || DEFAULT_DB_PATH;
}
const NOW = "to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')";

/** The application's SQL, said the way PostgreSQL says it. */
function translate(sql) {
  let out = sql
    // datetime('now', '-30 days')
    .replace(/datetime\(\s*'now'\s*,\s*'([+-])\s*(\d+)\s+(day|hour|minute|second|month|year)s?'\s*\)/gi, (_, sign, n, unit) => `to_char((now() AT TIME ZONE 'UTC') ${sign} interval '${n} ${unit}', 'YYYY-MM-DD HH24:MI:SS')`)
    .replace(/datetime\(\s*'now'\s*\)/gi, NOW)
    // The stored text is UTC and so is the server: "local time" of a stored moment is the text itself.
    .replace(/datetime\(\s*([A-Za-z_][\w.]*)\s*,\s*'localtime'\s*\)/gi, '$1')
    .replace(/json_group_array\(\s*json_object\(([^()]*)\)\s*\)/gi, (_, args) => `coalesce(json_agg(json_build_object(${args})), '[]'::json)::text`)
    // CAST(text AS INTEGER) of something that is not a number is 0 in SQLite and an error in PostgreSQL.
    // One level of brackets inside is enough for what the application writes: CAST(substr(a.link, 9) AS INTEGER).
    .replace(/CAST\(\s*((?:[^()]|\([^()]*\))+?)\s+AS\s+INTEGER\s*\)/gi, (_, expr) => `(CASE WHEN (${expr})::text ~ '^-?[0-9]+$' THEN (${expr})::text::integer ELSE 0 END)`)
    // "x IS ?" is SQLite's way to compare with a value that may be NULL.
    .replace(/\bIS\s+NOT\s+\?/gi, 'IS DISTINCT FROM ?')
    .replace(/\bIS\s+\?/gi, 'IS NOT DISTINCT FROM ?')
    // SQLite's LIKE does not tell A from a; PostgreSQL's does, and ILIKE is the one that does not.
    .replace(/\bLIKE\b/g, 'ILIKE');
  if (/^\s*INSERT\s+OR\s+IGNORE\b/i.test(out)) out = `${out.replace(/^\s*INSERT\s+OR\s+IGNORE\b/i, 'INSERT').replace(/;\s*$/, '')} ON CONFLICT DO NOTHING`;
  // "?" becomes $1, $2 ... outside quoted text.
  let n = 0;
  let quoted = false;
  let res = '';
  for (const ch of out) {
    if (ch === "'") quoted = !quoted;
    res += ch === '?' && !quoted ? `$${++n}` : ch;
  }
  return res;
}

/** schema.sql, written for SQLite, as PostgreSQL takes it. */
function translateSchema(sql) {
  return translate(
    sql
      .replace(/^\s*PRAGMA[^;]*;/gim, '')
      .replace(/INTEGER PRIMARY KEY AUTOINCREMENT/gi, 'integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
      .replace(/\bREAL\b/g, 'double precision')
      // Moments kept as milliseconds do not fit PostgreSQL's four-byte integer.
      .replace(/\b(expires_at|used_at|created_at) INTEGER\b/g, '$1 bigint')
  );
}

// ---- the two ways to reach PostgreSQL -----------------------------------------------------------------------
// Each gives `query(sql, params) -> { rows, rowCount }` and `transaction(fn)`, where fn gets a query bound to
// the transaction's own connection.

async function openServer(url) {
  const pg = require('pg');
  // Counts and sums arrive as text by default, because they may not fit a JavaScript number. Here they do.
  pg.types.setTypeParser(20, Number);
  pg.types.setTypeParser(1700, Number);
  // A host that runs many copies must keep few connections each: the server has one limit for all of them.
  const pool = new pg.Pool({ connectionString: url, max: Number(process.env.DB_POOL_MAX) || 3, idleTimeoutMillis: 5000 });
  // A resting connection may be closed from the other end; without a listener that would stop the process.
  pool.on('error', () => {});
  const shape = (r) => ({ rows: r.rows || [], rowCount: r.rowCount || 0 });
  return {
    kind: 'server',
    query: async (sql, params) => shape(await pool.query(sql, params)),
    exec: (sql) => pool.query(sql),
    async transaction(fn) {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const result = await fn(async (sql, params) => shape(await client.query(sql, params)));
        await client.query('COMMIT');
        return result;
      } catch (err) {
        await client.query('ROLLBACK').catch(() => {});
        throw err;
      } finally {
        client.release();
      }
    },
    close: () => pool.end(),
  };
}

async function openEmbedded(dir) {
  // Named in two pieces on purpose: a bundler that packs the hosted function must not pack this in. The
  // hosted application always has DATABASE_URL and never comes here.
  const { PGlite } = await import(['@electric-sql', 'pglite'].join('/'));
  if (dir !== 'memory://') fs.mkdirSync(dir, { recursive: true });
  const db = new PGlite(dir === 'memory://' ? undefined : dir, { parsers: { 20: Number, 1700: Number } });
  await db.waitReady;
  const shape = (r) => ({ rows: r.rows || [], rowCount: r.affectedRows ?? (r.rows ? r.rows.length : 0) });
  return {
    kind: 'embedded',
    query: async (sql, params) => shape(await db.query(sql, params)),
    exec: (sql) => db.exec(sql),
    transaction: (fn) => db.transaction((tx) => fn(async (sql, params) => shape(await tx.query(sql, params)))),
    close: () => db.close(),
  };
}

// ---- opening, once ------------------------------------------------------------------------------------------
async function open() {
  const url = process.env.DATABASE_URL;
  const backend = url ? await openServer(url) : await openEmbedded(embeddedPath());
  // A host that starts the application often must not be what changes the schema: there, the schema is
  // applied by a step of its own (npm run db:migrate) and DB_SKIP_SCHEMA=1 is set.
  if (process.env.DB_SKIP_SCHEMA !== '1') {
    await backend.exec(translateSchema(fs.readFileSync(path.join(__dirname, 'schema.sql'), 'utf8')));
    // A column added to schema.sql after a table existed.
    await backend.exec('ALTER TABLE decision_options ADD COLUMN IF NOT EXISTS risks TEXT');
    await backend.exec(`
      ALTER TABLE users ADD COLUMN IF NOT EXISTS timezone TEXT;
      ALTER TABLE users ADD COLUMN IF NOT EXISTS reminder_prefs TEXT NOT NULL DEFAULT '{}';
      ALTER TABLE tasks ADD COLUMN IF NOT EXISTS reminder_mode TEXT NOT NULL DEFAULT 'default';
      ALTER TABLE bills ADD COLUMN IF NOT EXISTS reminder_mode TEXT NOT NULL DEFAULT 'default';
      ALTER TABLE bills ADD COLUMN IF NOT EXISTS reminder_minutes_before INTEGER;
      ALTER TABLE goals ADD COLUMN IF NOT EXISTS reminder_mode TEXT NOT NULL DEFAULT 'default';
      ALTER TABLE goals ADD COLUMN IF NOT EXISTS reminder_minutes_before INTEGER;
      -- A number stored before the mode existed was a choice. It can only match once: afterwards every
      -- 'default' row has no number.
      UPDATE tasks SET reminder_mode = 'custom' WHERE reminder_mode = 'default' AND reminder_minutes_before IS NOT NULL;
      ALTER TABLE family_members ADD COLUMN IF NOT EXISTS muted_until TEXT;
      ALTER TABLE notifications ADD COLUMN IF NOT EXISTS push_status TEXT;
      ALTER TABLE notifications ADD COLUMN IF NOT EXISTS family_id INTEGER REFERENCES families(id) ON DELETE SET NULL;
      ALTER TABLE notifications ADD COLUMN IF NOT EXISTS push_kind TEXT;
      ALTER TABLE notifications ADD COLUMN IF NOT EXISTS push_attempts INTEGER NOT NULL DEFAULT 0;
      ALTER TABLE notifications ADD COLUMN IF NOT EXISTS push_retry_at TEXT;
      ALTER TABLE notifications ADD COLUMN IF NOT EXISTS push_claim TEXT;
      ALTER TABLE planned_reminders ADD COLUMN IF NOT EXISTS claim_token TEXT;
      ALTER TABLE planned_reminders ADD COLUMN IF NOT EXISTS attempts INTEGER NOT NULL DEFAULT 0;
      ALTER TABLE planned_reminders ADD COLUMN IF NOT EXISTS last_error TEXT;
      -- Only the three known choices can be stored, whoever writes the row.
      DO $$
      DECLARE t text;
      BEGIN
        FOREACH t IN ARRAY ARRAY['tasks', 'bills', 'goals'] LOOP
          IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = t || '_reminder_mode_check') THEN
            EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I CHECK (reminder_mode IN (''default'', ''none'', ''custom''))', t, t || '_reminder_mode_check');
          END IF;
        END LOOP;
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'planned_reminders_status_check') THEN
          ALTER TABLE planned_reminders ADD CONSTRAINT planned_reminders_status_check CHECK (status IN ('pending', 'claimed', 'sent', 'cancelled', 'failed'));
        END IF;
      END $$;
    `);
    await hardenFamilies(backend);
  }
  return backend;
}

// --- Family integrity hardening (Hardening 1: F-03, F-13) ----------------------
// Idempotent, non-destructive, and never fatal to start-up.
//  1. Legacy invite codes are exactly 8 characters. Every such code is replaced once with a strong
//     12-character code, in one transaction; the old code stops working. Codes of any other length are never
//     touched, so a restart cannot rotate a family again. Only the count is logged.
//  2. A family whose owner demoted themself through the old role endpoint has no member with role 'owner'
//     although families.owner_id still names one. The RECORDED owner (never anyone else) gets the role back
//     if they are still a member.
//  3. A partial unique index keeps "at most one owner per family" true at the database level. If existing
//     data already violated it, the index is skipped.
async function hardenFamilies(backend) {
  try {
    const { generateInviteCode } = require('../lib/inviteCode');
    const legacy = (await backend.query('SELECT id FROM families WHERE length(invite_code) = 8')).rows;
    if (legacy.length) {
      await backend.transaction(async (q) => {
        for (const f of legacy) {
          let code;
          do {
            code = generateInviteCode();
          } while ((await q('SELECT 1 FROM families WHERE invite_code = $1', [code])).rows.length);
          await q('UPDATE families SET invite_code = $1 WHERE id = $2', [code, f.id]);
        }
      });
      console.log(`[LifeAdmin] Replaced ${legacy.length} legacy 8-character invite code(s) with 12-character codes.`);
    }
    const repaired = await backend.query(
      `UPDATE family_members SET role = 'owner'
       WHERE role <> 'owner'
         AND user_id = (SELECT f.owner_id FROM families f WHERE f.id = family_members.family_id)
         AND NOT EXISTS (SELECT 1 FROM family_members o WHERE o.family_id = family_members.family_id AND o.role = 'owner')`
    );
    if (repaired.rowCount) console.log(`[LifeAdmin] Restored the recorded owner role in ${repaired.rowCount} family(ies).`);
    await backend.exec("CREATE UNIQUE INDEX IF NOT EXISTS idx_family_one_owner ON family_members(family_id) WHERE role = 'owner'");
  } catch (err) {
    console.error('[LifeAdmin] Family integrity hardening skipped:', err.message);
  }
}

let opening;
/** The database, opened on first use and kept. A failure is not kept: the next call tries again. */
function ready() {
  opening ??= open().catch((err) => {
    opening = undefined;
    throw err;
  });
  return opening;
}

// Inside `tx`, every helper call made by the function, however deep, runs on the transaction's connection.
const inTx = new AsyncLocalStorage();
async function query(sql, params, suffix = '') {
  const q = inTx.getStore();
  const text = translate(sql).replace(/;\s*$/, '') + suffix;
  try {
    return await (q ? q(text, params) : (await ready()).query(text, params));
  } catch (err) {
    // DB_DEBUG=1 says which statement failed; never on by default, a statement's values can be personal.
    if (process.env.DB_DEBUG === '1') console.error('[db]', err.code, err.message, '|', text.replace(/\s+/g, ' ').slice(0, 400), '|', JSON.stringify(params));
    // A value that is not a number where a number is compared ("/tasks/abc"): SQLite found no such row and
    // the application was written to that; PostgreSQL refuses the statement. Outside a transaction the old
    // answer is given: nothing matched. Inside one the refusal stands, because PostgreSQL has already
    // ended that transaction.
    if (err.code === '22P02' && !q) return { rows: [], rowCount: 0 };
    throw err;
  }
}

// --- Small query helpers -------------------------------------------------
/**
 * A statement that changes rows. Answers as SQLite's did: `changes` (rows touched) and, for an INSERT,
 * `lastInsertRowid` (the new row's id).
 */
async function run(sql, params = []) {
  const insert = /^\s*INSERT\b/i.test(sql) && !/\bRETURNING\b/i.test(sql);
  // Asked for after the translation, so that it follows whatever the translation put at the end.
  const result = await query(sql, params, insert ? ' RETURNING *' : '');
  return { changes: result.rowCount, lastInsertRowid: insert ? result.rows[0]?.id : undefined };
}

/** The first row, or undefined. */
async function get(sql, params = []) {
  return (await query(sql, params)).rows[0];
}

async function all(sql, params = []) {
  return (await query(sql, params)).rows;
}

/** Everything `fn` does through these helpers happens together or not at all. */
async function tx(fn) {
  if (inTx.getStore()) return fn();
  return (await ready()).transaction((q) => inTx.run(q, fn));
}

/** Several statements at once, without parameters: for the schema and for tests that prepare a state. */
async function exec(sql) {
  return (await ready()).exec(translate(sql));
}

async function close() {
  if (!opening) return;
  const backend = await opening.catch(() => null);
  opening = undefined;
  if (backend) await backend.close();
}

module.exports = { run, get, all, tx, exec, ready, close, translate, translateSchema, DB_PATH };
